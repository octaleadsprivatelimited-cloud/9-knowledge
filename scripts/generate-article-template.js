/**
 * Run after `vite build`. Reads dist/index.html and produces api/article-page-template.js
 * with a placeholder {{ARTICLE_META_BLOCK}} so the article-page API can inject
 * article-specific or site-default meta tags into the initial HTML.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const distPath = path.join(__dirname, '..', 'dist', 'index.html');
const outPath = path.join(__dirname, '..', 'api', 'article-page-template.js');

if (!fs.existsSync(distPath)) {
  console.error('generate-article-template: dist/index.html not found. Run "vite build" first.');
  process.exit(1);
}

const html = fs.readFileSync(distPath, 'utf8');

// Replace from <title> through the canonical link (inclusive) with a single placeholder.
// This preserves the rest of the document (favicon, preconnect, body, script).
const blockRegex = /<title>[\s\S]*?<link rel="canonical" href="[^"]*"\s*\/>/;
const replacement = '{{ARTICLE_META_BLOCK}}';
const newHtml = html.replace(blockRegex, replacement);

if (newHtml === html) {
  console.warn('generate-article-template: no match for meta block in index.html; output may be wrong.');
}

const escaped = newHtml.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$/g, '\\$');
const js = `/** Generated by scripts/generate-article-template.js - do not edit by hand */\nexport const HTML_TEMPLATE = \`${escaped}\`;\n`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, js, 'utf8');
console.log('generate-article-template: wrote api/article-page-template.js');
